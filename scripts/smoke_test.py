"""End-to-end toolchain smoke test: synthetic EEG -> 1D-CNN -> INT8 TFLite -> C header.

Classes: 0 = alpha-dominant (8-12 Hz), 1 = beta-dominant (13-30 Hz), single channel,
2 s windows at 128 Hz. Not a real EEG model; it only proves the pipeline works.
Writes firmware/eeg_smoke/model.h (model bytes + one test window per class).
"""
from pathlib import Path

import numpy as np
import tensorflow as tf

FS, WIN = 128, 256
ROOT = Path(__file__).resolve().parents[1]
OUT = ROOT / "firmware" / "eeg_smoke" / "model.h"
rng = np.random.default_rng(0)


def make_window(label: int) -> np.ndarray:
    t = np.arange(WIN) / FS
    f = rng.uniform(8, 12) if label == 0 else rng.uniform(13, 30)
    sig = np.sin(2 * np.pi * f * t + rng.uniform(0, 2 * np.pi))
    sig += 0.6 * rng.standard_normal(WIN)  # broadband noise
    sig += 0.3 * np.cumsum(rng.standard_normal(WIN)) / np.sqrt(WIN)  # slow drift
    return ((sig - sig.mean()) / (sig.std() + 1e-6)).astype(np.float32)


def dataset(n: int):
    y = rng.integers(0, 2, n)
    x = np.stack([make_window(int(l)) for l in y])[..., None]
    return x, y


x_train, y_train = dataset(3000)
x_test, y_test = dataset(600)

model = tf.keras.Sequential([
    tf.keras.Input((WIN, 1)),
    tf.keras.layers.Conv1D(8, 7, strides=2, activation="relu"),
    tf.keras.layers.MaxPooling1D(2),
    tf.keras.layers.Conv1D(16, 5, strides=2, activation="relu"),
    tf.keras.layers.MaxPooling1D(2),
    tf.keras.layers.Flatten(),
    tf.keras.layers.Dense(16, activation="relu"),
    tf.keras.layers.Dense(2, activation="softmax"),
])
model.compile("adam", "sparse_categorical_crossentropy", metrics=["accuracy"])
model.fit(x_train, y_train, epochs=8, batch_size=64, verbose=0)
fp32_acc = model.evaluate(x_test, y_test, verbose=0)[1]

conv = tf.lite.TFLiteConverter.from_keras_model(model)
conv.optimizations = [tf.lite.Optimize.DEFAULT]
conv.representative_dataset = lambda: ([x[None]] for x in x_train[:300])
conv.target_spec.supported_ops = [tf.lite.OpsSet.TFLITE_BUILTINS_INT8]
conv.inference_input_type = tf.int8
conv.inference_output_type = tf.int8
tflite = conv.convert()

interp = tf.lite.Interpreter(model_content=tflite)
interp.allocate_tensors()
inp, out = interp.get_input_details()[0], interp.get_output_details()[0]
s_in, z_in = inp["quantization"]


def q(x):
    return np.clip(np.round(x / s_in + z_in), -128, 127).astype(np.int8)


correct = 0
for x, y in zip(x_test, y_test):
    interp.set_tensor(inp["index"], q(x)[None])
    interp.invoke()
    correct += int(np.argmax(interp.get_tensor(out["index"])[0]) == y)
int8_acc = correct / len(y_test)

samples = {c: q(x_test[np.argmax(y_test == c)]).ravel() for c in (0, 1)}


def carr(name, ctype, data, align=False):
    body = ",".join(str(int(v)) for v in data)
    a = "alignas(16) " if align else ""
    return f"{a}const {ctype} {name}[] = {{{body}}};\nconst unsigned int {name}_len = {len(data)};\n"


OUT.parent.mkdir(parents=True, exist_ok=True)
OUT.write_text(
    "// Generated by scripts/smoke_test.py -- do not edit\n#pragma once\n#include <stdint.h>\n"
    + carr("g_model", "unsigned char", tflite, align=True)
    + carr("g_sample_alpha", "int8_t", samples[0])
    + carr("g_sample_beta", "int8_t", samples[1])
)
print(f"FP32 acc {fp32_acc:.3f} | INT8 acc {int8_acc:.3f} | model {len(tflite)} bytes -> {OUT}")
