"""Write reference vectors for checking the firmware against Python (REQ-FEAT-09).

A fixed synthetic 12 s signal (alpha, delta, a spindle burst, noise, 60 Hz hum,
DC offset and drift) goes through eegml; the raw samples, filter coefficients,
filtered samples and per-window features are saved as JSON (for tests) and as a
C header (for the firmware's on-device parity test).
    python scripts/export_test_vectors.py
"""
import json
import sys
from pathlib import Path

import numpy as np

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))
from eegml import config, filters  # noqa: E402
from eegml.features import FEATURE_NAMES, sliding_features  # noqa: E402

VERSION = 1
JSON_OUT = ROOT / "tests" / "vectors" / f"feature_vectors_v{VERSION}.json"
H_OUT = ROOT / "firmware" / "test_vectors" / f"feature_vectors_v{VERSION}.h"


def make_signal(seconds: float = 12.0, fs: float = config.FS, seed: int = 635):
    rng = np.random.default_rng(seed)
    t = np.arange(int(seconds * fs)) / fs
    x = (15 * np.sin(2 * np.pi * 10 * t)                      # alpha, uV
         + 8 * np.sin(2 * np.pi * 2 * t + 0.3)                 # delta
         + 6 * np.sin(2 * np.pi * 13 * t) * ((t > 5) & (t < 7))  # spindle burst
         + 4 * rng.standard_normal(len(t))                     # background
         + 20 * np.sin(2 * np.pi * 60 * t)                     # mains hum
         + 200 + 30 * t / seconds)                             # electrode offset + drift
    return x


def build():
    raw = make_signal()
    sos = filters.design_sos()
    filt = filters.apply(raw, sos=sos)
    starts, feats = sliding_features(filt, raw)
    return {"version": VERSION, "fs": config.FS, "win_s": config.WIN_S, "hop_s": config.HOP_S,
            "nfft": config.NFFT, "bands": config.BANDS, "feature_names": FEATURE_NAMES,
            "sos": sos.tolist(), "raw_uv": raw.tolist(), "filtered_uv": filt.tolist(),
            "window_starts": starts.tolist(), "features": feats.tolist()}


def carr(name, data, ctype="float"):
    vals = ",".join(f"{v:.9g}f" for v in np.ravel(data))
    return f"static const {ctype} {name}[{np.size(data)}] = {{{vals}}};\n"


def main():
    v = build()
    JSON_OUT.parent.mkdir(parents=True, exist_ok=True)
    JSON_OUT.write_text(json.dumps(v))
    H_OUT.parent.mkdir(parents=True, exist_ok=True)
    feats = np.array(v["features"])
    h = ["// Generated by scripts/export_test_vectors.py - do not edit.\n#pragma once\n",
         f"#define TV_VERSION {VERSION}\n#define TV_FS {v['fs']:g}f\n",
         f"#define TV_N_SAMPLES {len(v['raw_uv'])}\n#define TV_N_SOS {len(v['sos'])}\n",
         f"#define TV_N_WINDOWS {feats.shape[0]}\n#define TV_N_FEATURES {feats.shape[1]}\n",
         "// Feature order: " + ", ".join(FEATURE_NAMES) + "\n",
         carr("tv_sos", v["sos"]), carr("tv_raw_uv", v["raw_uv"]),
         carr("tv_filtered_uv", v["filtered_uv"]), carr("tv_features", feats)]
    H_OUT.write_text("".join(h))
    print(f"wrote {JSON_OUT.relative_to(ROOT)} and {H_OUT.relative_to(ROOT)}: "
          f"{len(v['raw_uv'])} samples, {feats.shape[0]} windows x {feats.shape[1]} features")


if __name__ == "__main__":
    main()
