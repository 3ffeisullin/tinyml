"""Write reference vectors for checking the firmware against Python (REQ-FEAT-09).

A fixed synthetic 12 s signal (alpha, delta, a spindle burst, noise, 60 Hz hum,
DC offset and drift) goes through eegml; the raw samples, filter coefficients,
filtered samples and per-window features are saved as JSON (for tests) and as a
C header (for the firmware's on-device parity test). Also writes
firmware/eeg_node/eeg_config.h, the C copy of eegml/config.py that the node
firmware uses, and a copy of the vectors header next to the eeg_node sketch
(Arduino can't include files from outside the sketch folder).
    python scripts/export_test_vectors.py
"""
import json
import sys
from pathlib import Path

import numpy as np

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))
from eegml import acquisition, config, filters  # noqa: E402
from eegml.features import FEATURE_NAMES, sliding_features  # noqa: E402

VERSION = 1
JSON_OUT = ROOT / "tests" / "vectors" / f"feature_vectors_v{VERSION}.json"
H_OUT = ROOT / "firmware" / "test_vectors" / f"feature_vectors_v{VERSION}.h"
NODE_DIR = ROOT / "firmware" / "eeg_node"
H_NODE_COPY = NODE_DIR / f"feature_vectors_v{VERSION}.h"
CONFIG_H = NODE_DIR / "eeg_config.h"


def make_signal(seconds: float = 12.0, fs: float = config.FS, seed: int = 635):
    rng = np.random.default_rng(seed)
    t = np.arange(int(seconds * fs)) / fs
    x = (15 * np.sin(2 * np.pi * 10 * t)                      # alpha, uV
         + 8 * np.sin(2 * np.pi * 2 * t + 0.3)                 # delta
         + 6 * np.sin(2 * np.pi * 13 * t) * ((t > 5) & (t < 7))  # spindle burst
         + 4 * rng.standard_normal(len(t))                     # background
         + 20 * np.sin(2 * np.pi * 60 * t)                     # mains hum
         + 200 + 30 * t / seconds)                             # electrode offset + drift
    return x


def build():
    raw = make_signal()
    sos = filters.design_sos()
    filt = filters.apply(raw, sos=sos)
    starts, feats = sliding_features(filt, raw)
    return {"version": VERSION, "fs": config.FS, "win_s": config.WIN_S, "hop_s": config.HOP_S,
            "nfft": config.NFFT, "bands": config.BANDS, "feature_names": FEATURE_NAMES,
            "sos": sos.tolist(), "raw_uv": raw.tolist(), "filtered_uv": filt.tolist(),
            "window_starts": starts.tolist(), "features": feats.tolist()}


def flit(v) -> str:
    """A valid C float literal: '1.0f', not '1f' (which doesn't compile)."""
    s = f"{float(v):.9g}"
    if not any(c in s for c in ".eEn"):
        s += ".0"
    return s + "f"


def carr(name, data, ctype="float"):
    lit = flit if ctype == "float" else (lambda v: repr(float(v)))  # double: full precision
    vals = ",".join(lit(v) for v in np.ravel(data))
    return f"static const {ctype} {name}[{np.size(data)}] = {{{vals}}};\n"


def config_header() -> str:
    """eegml/config.py as C constants (REQ-FEAT-01..04): the firmware's only source of these values."""
    from eegml.features import FEATURE_NAMES as names
    sos60 = filters.design_sos(config.FilterSpec(line_freq=60.0))
    sos50 = filters.design_sos(config.FilterSpec(line_freq=50.0))
    lines = ["// Generated by scripts/export_test_vectors.py from eegml/config.py - do not edit.",
             "#pragma once", "",
             f"#define EEG_FS {flit(config.FS)}",
             f"#define EEG_WIN {int(round(config.WIN_S * config.FS))}",
             f"#define EEG_HOP {int(round(config.HOP_S * config.FS))}",
             f"#define EEG_NFFT {config.NFFT}",
             f"#define EEG_EPOCH {int(round(config.EPOCH_S * config.FS))}",
             f"#define EEG_EPS {flit(config.EPS)}",
             f"#define EEG_LINE_HALF_WIDTH {flit(config.LINE_BAND_HALF_WIDTH)}",
             f"#define EEG_TOTAL_LO {flit(config.TOTAL_BAND[0])}",
             f"#define EEG_TOTAL_HI {flit(config.TOTAL_BAND[1])}",
             f"#define EEG_N_BANDS {len(config.BANDS)}",
             f"#define EEG_N_FEATURES {len(names)}",
             "// Bands, half-open [lo, hi) Hz: " + ", ".join(config.BANDS),
             "static const float EEG_BAND_LO[EEG_N_BANDS] = {" + ", ".join(flit(lo) for lo, _ in config.BANDS.values()) + "};",
             "static const float EEG_BAND_HI[EEG_N_BANDS] = {" + ", ".join(flit(hi) for _, hi in config.BANDS.values()) + "};",
             "// Window feature order: " + ", ".join(names),
             "// ADS1115 front end (REQ-HW-02/03, REQ-ACQ-01/02); config words from eegml/acquisition.py.",
             f"#define EEG_ADC_I2C_ADDR 0x{config.ADC_I2C_ADDR:02X}",
             f"#define EEG_ADC_I2C_HZ {config.ADC_I2C_HZ}",
             f"#define EEG_ADC_SPS {config.ADC_SPS}",
             f"#define EEG_ADC_CONFIG_DIFF 0x{acquisition.CONFIG_DIFF:04X}  // A0-A1, +-{config.ADC_PGA_FS_V:g} V, {config.ADC_SPS} SPS, RDY",
             f"#define EEG_ADC_CONFIG_SINGLE 0x{acquisition.CONFIG_SINGLE:04X}  // A0-GND, +-{config.ADC_FALLBACK_PGA_FS_V:g} V (fallback)",
             f"#define EEG_ADC_LSB_UV_DIFF {flit(acquisition.lsb_uv(config.ADC_PGA_FS_V))}",
             f"#define EEG_ADC_LSB_UV_SINGLE {flit(acquisition.lsb_uv(config.ADC_FALLBACK_PGA_FS_V))}",
             f"#define EEG_PILL_GAIN {flit(config.PILL_GAIN)}  // PLACEHOLDER until bench calibration (REQ-ACQ-01)",
             "// Filter chain (b0, b1, b2, a0, a1, a2 per section): notches, high-pass, low-pass.",
             "// Double precision: float32 coefficients and state put skew out of tolerance on the board",
             "// (the 0.5 Hz high-pass poles sit close to the unit circle). Found in task 6, 2026-11-21.",
             f"#define EEG_N_SOS_60 {len(sos60)}",
             carr("EEG_SOS_60", sos60, "double").rstrip(),
             f"#define EEG_N_SOS_50 {len(sos50)}",
             carr("EEG_SOS_50", sos50, "double").rstrip(), ""]
    return "\n".join(lines)


def main():
    v = build()
    JSON_OUT.parent.mkdir(parents=True, exist_ok=True)
    JSON_OUT.write_text(json.dumps(v))
    H_OUT.parent.mkdir(parents=True, exist_ok=True)
    feats = np.array(v["features"])
    h = ["// Generated by scripts/export_test_vectors.py - do not edit.\n#pragma once\n",
         f"#define TV_VERSION {VERSION}\n#define TV_FS {flit(v['fs'])}\n",
         f"#define TV_N_SAMPLES {len(v['raw_uv'])}\n#define TV_N_SOS {len(v['sos'])}\n",
         f"#define TV_N_WINDOWS {feats.shape[0]}\n#define TV_N_FEATURES {feats.shape[1]}\n",
         "// Feature order: " + ", ".join(FEATURE_NAMES) + "\n",
         carr("tv_sos", v["sos"]), carr("tv_raw_uv", v["raw_uv"]),
         carr("tv_filtered_uv", v["filtered_uv"]), carr("tv_features", feats)]
    H_OUT.write_text("".join(h))
    NODE_DIR.mkdir(parents=True, exist_ok=True)
    H_NODE_COPY.write_text("".join(h))
    CONFIG_H.write_text(config_header())
    print(f"wrote {JSON_OUT.relative_to(ROOT)} and {H_OUT.relative_to(ROOT)}: "
          f"{len(v['raw_uv'])} samples, {feats.shape[0]} windows x {feats.shape[1]} features")


if __name__ == "__main__":
    main()
