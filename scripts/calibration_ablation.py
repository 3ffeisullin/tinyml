"""How much does realistic calibration cost the sleep model? (REQ-FEAT-10, REQ-ML-03)

reports/sleep_model.md standardises each subject with its whole-night mean/SD,
which the device can never know. This re-runs the same 5-fold leave-subjects-out
split and scores held-out subjects with stats from:
  * the whole night (as in the report),
  * the first 60 s / 5 min / 10 min of the recording (REQ-FEAT-10 as written;
    in Sleep-EDF these epochs are wake, up to 30 min before sleep onset),
  * a running (expanding) mean/SD up to the current epoch, warm-up 10 epochs,
for the model trained on whole-night stats, and for models trained the same way
as they are tested (5 min, running).

    .\\venv\\Scripts\\python.exe scripts\\calibration_ablation.py
Writes reports/calibration_ablation.md and .json. Float models only.
"""
import json
import sys
from pathlib import Path

import numpy as np
from sklearn.metrics import accuracy_score, f1_score, recall_score
from sklearn.model_selection import GroupKFold

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT)); sys.path.insert(0, str(ROOT / "scripts"))
import train_sleep_model as T  # noqa: E402
from eegml import sleep_model as sm  # noqa: E402
from eegml.sleep_edf import STAGE_NAMES  # noqa: E402

WARM = sm.WARMUP


def running(x):
    """Device behaviour (eegml.sleep_model.running_standardise, Welford)."""
    return sm.model_input(x, mode="running")


def first_n(x, n):
    return sm.model_input(x, x[:n].mean(0), x[:n].std(0))


VARIANTS = {"whole night": lambda x: sm.model_input(x, mode="whole-night"), "first 60 s": lambda x: first_n(x, 2),
            "first 5 min": lambda x: first_n(x, 10), "first 10 min": lambda x: first_n(x, 20),
            "running": running}
RETRAINED = {"trained+tested on first 5 min": "first 5 min", "trained+tested on running": "running"}


def main():
    sys.stdout.reconfigure(encoding="utf-8", errors="replace")
    cache = ROOT / "data" / "cache" / "sleep_edf"
    raws, ys = [], []
    for s in range(20):
        d = np.load(cache / f"sc{s:02d}.npz"); raws.append(d["ours"]); ys.append(d["y"])
    g = np.concatenate([np.full(len(v), i) for i, v in enumerate(ys)]); y = np.concatenate(ys)
    X = {k: np.vstack([f(r) for r in raws]) for k, f in VARIANTS.items()}
    rng = np.random.default_rng(T.SEED)
    pred = {k: np.empty_like(y) for k in [*(f"trained on whole night, tested on {k}" for k in VARIANTS), *RETRAINED]}
    for k_fold, (tr, te) in enumerate(GroupKFold(5).split(X["whole night"], y, g)):
        m, _ = T.fit_float(X["whole night"][tr], y[tr], g[tr], rng, 150)
        for k in VARIANTS:
            pred[f"trained on whole night, tested on {k}"][te] = m.predict(X[k][te], verbose=0).argmax(1)
        for k, src in RETRAINED.items():
            m2, _ = T.fit_float(X[src][tr], y[tr], g[tr], rng, 150)
            pred[k][te] = m2.predict(X[src][te], verbose=0).argmax(1)
        print(f"  fold {k_fold} done", flush=True)
    labels = list(range(5))
    res = {k: {"accuracy": float(accuracy_score(y, p)),
               "macro_f1": float(f1_score(y, p, average="macro", labels=labels, zero_division=0)),
               "recall": dict(zip(STAGE_NAMES, recall_score(y, p, average=None, labels=labels,
                                                            zero_division=0).round(3).tolist()))}
           for k, p in pred.items()}
    out = ROOT / "reports"
    (out / "calibration_ablation.json").write_text(json.dumps(res, indent=2))
    rows = ["| Standardisation | Accuracy | Macro F1 | " + " | ".join(f"Recall {s}" for s in STAGE_NAMES) + " |",
            "|---|---|---|" + "---|" * 5]
    rows += [f"| {k} | {r['accuracy']:.3f} | {r['macro_f1']:.3f} | "
             + " | ".join(f"{r['recall'][s]:.2f}" for s in STAGE_NAMES) + " |" for k, r in res.items()]
    md = f"""# Calibration ablation for the sleep model (REQ-FEAT-10)

Float dense net from `scripts/train_sleep_model.py`, 20 subjects, the same 5-fold leave-subjects-out
split. Only the per-subject standardisation statistics change. Generated by `scripts/calibration_ablation.py`.

{chr(10).join(rows)}

Baseline random forest (raw features, no standardisation): accuracy 0.774, macro F1 0.680.

**Reading:** the model in `reports/sleep_model.md` relies on whole-night statistics. With statistics
from a short calibration at the start of the recording (wake), it falls well below the random forest.
A causal running mean/SD (device: Welford update over 30 values per epoch, {WARM}-epoch warm-up),
used for training as well as testing, keeps most of the gain and still beats the random forest.
"""
    (out / "calibration_ablation.md").write_text(md, encoding="utf-8")
    print(md)


if __name__ == "__main__":
    main()
